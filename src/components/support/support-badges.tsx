import React from 'react';
import { BadgeCheck, Sparkles } from 'lucide-react';
import { TicketStatus } from '../../services/local-api';

/**
 * AI answers and Security Team responses are always labelled differently, so nobody
 * mistakes generated text for a reviewed answer (or the other way round).
 */
export const AiAnswerBadge: React.FC = () => (
  <span className="bm-chip" title="Generated by the Policy Copilot from approved policy text. Check the cited sources.">
    <Sparkles className="h-3 w-3" aria-hidden="true" /> AI-generated
  </span>
);

export const SecurityTeamBadge: React.FC<{ agentId?: string | null; kind?: 'response' | 'guidance' }> = ({ agentId, kind }) => (
  <span className="bm-chip bm-sev bm-sev-safe" title="Written by a member of the XYZ Security Team">
    <BadgeCheck className="h-3 w-3" aria-hidden="true" />
    Security Team {kind === 'guidance' ? 'guidance' : 'response'}
    {agentId && <span className="font-mono">· {agentId}</span>}
  </span>
);

const STATUS_STYLE: Record<TicketStatus, { label: string; className: string }> = {
  open: { label: 'Open', className: 'bm-sev-low' },
  answered: { label: 'Answered', className: 'bm-sev-med' },
  resolved: { label: 'Resolved', className: 'bm-sev-safe' },
};

export const StatusChip: React.FC<{ status: TicketStatus }> = ({ status }) => <span className={`bm-chip bm-sev ${STATUS_STYLE[status].className}`}>{STATUS_STYLE[status].label}</span>;

export function formatWhen(iso: string): string {
  const date = new Date(iso);
  const minutes = Math.round((Date.now() - date.getTime()) / 60000);
  if (minutes < 1) return 'just now';
  if (minutes < 60) return `${minutes} min ago`;
  if (minutes < 60 * 24) return `${Math.round(minutes / 60)} h ago`;
  return date.toLocaleDateString(undefined, { month: 'short', day: 'numeric' });
}
